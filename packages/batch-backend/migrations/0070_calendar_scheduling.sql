-- Durable Calendar intents and identity. No executable local recurrence rules.
CREATE TABLE calendar_operations (
  id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES workspaces(id),
  connection_id uuid NOT NULL REFERENCES workspace_calendar_connections(id),
  connection_generation bigint NOT NULL,
  student_id uuid REFERENCES students(id),
  initiating_user_id uuid REFERENCES users(id),
  adopted_by uuid REFERENCES users(id),
  authority_policy text NOT NULL CHECK (authority_policy IN ('initiator','workspace_service')),
  parent_id uuid REFERENCES calendar_operations(id),
  kind text NOT NULL CHECK (kind IN ('setup','create','bind','sync','refresh')),
  idempotency_key text NOT NULL,
  request_hash text NOT NULL,
  request_payload jsonb NOT NULL DEFAULT '{}',
  provider_event_id text,
  association_marker text,
  slot_index integer,
  state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','running','retry_wait','succeeded','needs_review','superseded')),
  write_attempted_at timestamptz,
  lease_token uuid,
  lease_expires_at timestamptz,
  attempts integer NOT NULL DEFAULT 0,
  due_at timestamptz NOT NULL DEFAULT now(),
  error_code text,
  event_url text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(workspace_id,kind,idempotency_key)
);
CREATE INDEX calendar_operations_dispatch ON calendar_operations(due_at) WHERE state IN ('pending','running','retry_wait');
CREATE TABLE calendar_schedule_bindings (
  id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES workspaces(id),
  student_id uuid NOT NULL REFERENCES students(id),
  connection_id uuid NOT NULL REFERENCES workspace_calendar_connections(id),
  provider_event_id text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('one_off','series')),
  association_marker text NOT NULL,
  source_version text,
  setup_operation_id uuid REFERENCES calendar_operations(id),
  projected_until timestamptz,
  next_projection_at timestamptz NOT NULL DEFAULT now(),
  attention_code text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(connection_id,provider_event_id),
  UNIQUE(connection_id,association_marker)
);
CREATE TABLE calendar_lesson_bindings (
  lesson_id uuid PRIMARY KEY REFERENCES student_lessons(id),
  schedule_binding_id uuid NOT NULL REFERENCES calendar_schedule_bindings(id),
  connection_id uuid NOT NULL REFERENCES workspace_calendar_connections(id),
  provider_event_id text NOT NULL,
  recurring_event_id text,
  original_start_time text,
  source_version text,
  provider_updated_at timestamptz,
  provider_status text NOT NULL,
  canceled_by_calendar boolean NOT NULL DEFAULT false,
  event_url text,
  attention_code text,
  UNIQUE(connection_id,provider_event_id),
  UNIQUE(schedule_binding_id,original_start_time)
);
