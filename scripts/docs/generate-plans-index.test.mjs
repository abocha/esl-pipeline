import assert from 'node:assert/strict';
import fs, { readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';

import { generatePlansIndex } from './generate-plans-index.mjs';

test('plans-only generator writes plans index without touching unrelated generated indexes', async () => {
  const repoRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'plans-index-test-'));
  writeFile(repoRoot, 'scripts/docs/docs-check.config.json', JSON.stringify(config, null, 2));
  writeFile(repoRoot, 'docs/generated/plans-index.md', 'old plans\n');
  writeFile(repoRoot, 'docs/generated/backend-route-index.md', 'old routes\n');
  writeFile(
    repoRoot,
    'docs/plans/README.md',
    ['# Plans', '', '- `docs/plans/topic/README.md`', ''].join('\n'),
  );
  writeFile(
    repoRoot,
    'docs/plans/topic/README.md',
    [
      '# Topic Plan',
      '',
      '- Last Verified Against: 2026-05-18 repo state.',
      '- Status: `roadmap`.',
      '- Exit Trigger: archive after implementation PR merges.',
      '- Current Focus: edit this topic README only.',
      '',
    ].join('\n'),
  );

  await generatePlansIndex({ repoRoot });

  const plansIndex = readFileSync(path.join(repoRoot, 'docs/generated/plans-index.md'), 'utf8');
  const routeIndex = readFileSync(
    path.join(repoRoot, 'docs/generated/backend-route-index.md'),
    'utf8',
  );

  assert.match(plansIndex, /Generated by `pnpm docs:generate:plans-index`/);
  assert.match(plansIndex, /Current Focus/);
  assert.match(plansIndex, /edit this topic README only/);
  assert.equal(routeIndex, 'old routes\n');
});

const config = {
  docs_gardening: {
    plan_lifecycle: {
      route_source: 'docs/plans/README.md',
      allowed_active_statuses: ['active', 'roadmap', 'backlog', 'draft'],
      archive_prefix: 'docs/archive/plans/',
    },
  },
};

function writeFile(repoRoot, relativePath, contents) {
  const absolutePath = path.join(repoRoot, relativePath);
  fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
  writeFileSync(absolutePath, contents, 'utf8');
}
