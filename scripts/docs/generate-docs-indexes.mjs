import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { generatePlansIndex } from './generate-plans-index.mjs';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const docsCheckConfigPath = path.join(rootDir, 'scripts', 'docs', 'docs-check.config.json');

const docsCheckConfig = JSON.parse(await readFile(docsCheckConfigPath, 'utf8'));
const enforcedDocs = new Set([
  ...(docsCheckConfig.non_core_docs ?? []),
  ...(docsCheckConfig.active_ops_docs ?? []),
]);

async function walk(relativeDir, matcher) {
  const absoluteDir = path.join(rootDir, relativeDir);
  const entries = await readdir(absoluteDir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relativePath = path.posix.join(relativeDir.replaceAll(path.sep, '/'), entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(relativePath, matcher)));
      continue;
    }
    if (!matcher(relativePath)) {
      continue;
    }
    files.push(relativePath);
  }
  return files;
}

async function readMarkdownTitle(relativePath) {
  const contents = await readFile(path.join(rootDir, relativePath), 'utf8');
  const match = contents.match(/^#\s+(.+)$/m);
  return match ? match[1].trim() : path.basename(relativePath);
}

async function writeGenerated(relativePath, contents) {
  await writeFile(path.join(rootDir, relativePath), contents, 'utf8');
}

function posixRelative(relativePath) {
  return relativePath.replaceAll(path.sep, '/');
}

function formatGeneratedHeader(title, purpose, sourceNote) {
  return [
    `# ${title}`,
    '',
    '> Generated by `pnpm docs:generate:indexes`. Do not edit by hand.',
    '',
    '## Purpose',
    '',
    `- ${purpose}`,
    `- ${sourceNote}`,
    '',
  ].join('\n');
}

async function generatePackageReadmeIndex() {
  const packageDirs = (await readdir(path.join(rootDir, 'packages'), { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));

  const rows = [];
  for (const packageDir of packageDirs) {
    const readmePath = posixRelative(path.join('packages', packageDir, 'README.md'));
    const packageJsonPath = path.join(rootDir, 'packages', packageDir, 'package.json');
    try {
      await stat(path.join(rootDir, readmePath));
    } catch {
      continue;
    }
    const packageJson = JSON.parse(await readFile(packageJsonPath, 'utf8'));
    const title = await readMarkdownTitle(readmePath);
    rows.push({
      packageName: packageJson.name ?? packageDir,
      title,
      path: readmePath,
      enforced: enforcedDocs.has(readmePath) ? 'yes' : 'no',
    });
  }

  const lines = [
    formatGeneratedHeader(
      'Package README Index',
      'Provide a fast inventory of package-level README surfaces and whether they are part of the current docs enforcement scope.',
      'Package names come from `packages/*/package.json`; enforcement scope comes from `scripts/docs/docs-check.config.json`.',
    ),
    '## Packages',
    '',
    '| Package | README Title | Enforced | Path |',
    '| --- | --- | --- | --- |',
    ...rows.map(
      (row) => `| \`${row.packageName}\` | ${row.title} | ${row.enforced} | \`${row.path}\` |`,
    ),
    '',
  ];

  await writeGenerated('docs/generated/package-readme-index.md', lines.join('\n'));
}

async function extractEnvKeysFromExample(relativePath) {
  const contents = await readFile(path.join(rootDir, relativePath), 'utf8');
  const keys = new Set();
  for (const rawLine of contents.split('\n')) {
    const line = rawLine.trim();
    const candidate = line.startsWith('#') ? line.slice(1).trim() : line;
    const match = candidate.match(/^([A-Z0-9_]+)=/);
    if (match) {
      keys.add(match[1]);
    }
  }
  return [...keys].sort((left, right) => left.localeCompare(right));
}

function classifyEnvSurface(key) {
  if (key.startsWith('TELEGRAM_OPS_BOT_') || key.startsWith('BATCH_BACKEND_OPS_CONTROL_')) {
    return {
      surface: 'telegram_ops',
      details: 'docs/operations/telegram-ops-control-panel.md',
    };
  }

  if (key.startsWith('PG_BACKUP_') || key === 'PG_CONTAINER_NAME') {
    return {
      surface: 'postgres_ops',
      details: 'docs/operations/postgres-backup-restore.md',
    };
  }

  if (
    key.startsWith('GEN_') ||
    key === 'OPENAI_API_KEY' ||
    key === 'GEMINI_API_KEY' ||
    key === 'OPENROUTER_API_KEY' ||
    key === 'OPENROUTER_HTTP_REFERER' ||
    key === 'OPENROUTER_X_TITLE'
  ) {
    return {
      surface: 'generation_runtime',
      details: 'docs/reference/GENERATION_PROVIDER_POLICY.md',
    };
  }

  if (key.startsWith('ESL_STT_') || key.startsWith('TRANSCRIBE_') || key === 'STT_PROVIDER') {
    return {
      surface: 'speech_runtime',
      details: 'docs/reference/env.md',
    };
  }

  if (key.startsWith('ESL_TTS_') || key.startsWith('VOICE_ALIGNMENT_')) {
    return {
      surface: 'speech_runtime',
      details: 'docs/reference/env.md',
    };
  }

  if (
    key.startsWith('PG_') ||
    key.startsWith('REDIS_') ||
    key === 'BATCH_JOBS_QUEUE_NAME' ||
    key === 'TRANSCRIBE_QUEUE_NAME' ||
    key === 'WORKER_CONCURRENCY' ||
    key === 'MAX_CONCURRENT_FFMPEG' ||
    key === 'FILESYSTEM_UPLOAD_DIR' ||
    key === 'DRAFT_LOCAL_EXPORT' ||
    key === 'PIPELINE_CWD' ||
    key.startsWith('JWT_') ||
    key.startsWith('REFRESH_') ||
    key === 'BCRYPT_ROUNDS' ||
    key === 'MAX_FILE_SIZE' ||
    key === 'ALLOWED_MIME_TYPES' ||
    key.startsWith('UPLOAD_') ||
    key.startsWith('ENABLE_') ||
    key.startsWith('CORS_') ||
    key === 'SECURITY_HEADERS_ENABLED' ||
    key === 'HSTS_MAX_AGE' ||
    key === 'BATCH_BACKEND_HTTP_PORT' ||
    key === 'BATCH_BACKEND_ENABLE_EXTENDED_API' ||
    key === 'NODE_ENV'
  ) {
    return {
      surface: 'batch_backend',
      details: 'packages/batch-backend/README.md',
    };
  }

  if (
    key.startsWith('S3_') ||
    key.startsWith('AWS_') ||
    key.startsWith('STORAGE_') ||
    key.startsWith('ESL_PIPELINE_') ||
    key.startsWith('MINIO_') ||
    key.startsWith('MAIL_') ||
    key === 'LOG_LEVEL' ||
    key === 'RECORDINGS_MAX_FILE_SIZE'
  ) {
    return {
      surface: 'shared_runtime',
      details: 'docs/reference/env.md',
    };
  }

  return {
    surface: 'misc',
    details: 'docs/reference/env.md',
  };
}

async function generateEnvSurfaceIndex() {
  const exampleFiles = ['.env.example', '.env.batch-backend.example'];
  const rows = [];

  for (const exampleFile of exampleFiles) {
    const keys = await extractEnvKeysFromExample(exampleFile);
    for (const key of keys) {
      const classification = classifyEnvSurface(key);
      rows.push({
        key,
        exampleFile,
        surface: classification.surface,
        details: classification.details,
      });
    }
  }

  rows.sort((left, right) => {
    const keyOrder = left.key.localeCompare(right.key);
    if (keyOrder !== 0) return keyOrder;
    return left.exampleFile.localeCompare(right.exampleFile);
  });

  const lines = [
    formatGeneratedHeader(
      'Environment Surface Index',
      'Provide an exhaustive lookup table for env keys surfaced in the checked example env files without duplicating the policy narrative from `docs/reference/env.md`.',
      'Keys are extracted from `.env.example` and `.env.batch-backend.example`; surface ownership is classified by prefix and documented next-hop links.',
    ),
    '## Environment Keys',
    '',
    '| Key | Example File | Surface | Details |',
    '| --- | --- | --- | --- |',
    ...rows.map(
      (row) => `| \`${row.key}\` | \`${row.exampleFile}\` | ${row.surface} | \`${row.details}\` |`,
    ),
    '',
  ];

  await writeGenerated('docs/generated/env-surface-index.md', lines.join('\n'));
}

function collectRouteMatches(contents) {
  const regex = /app\.(get|post|put|patch|delete)\(\s*['"`]([^'"`]+)['"`]/g;
  const matches = [];
  let match;
  while ((match = regex.exec(contents)) !== null) {
    matches.push({
      method: match[1].toUpperCase(),
      path: match[2],
    });
  }
  return matches;
}

async function generateBackendRouteIndex() {
  const routeFiles = (
    await walk(
      'packages/batch-backend/src/transport',
      (relativePath) =>
        relativePath.endsWith('.ts') && !relativePath.endsWith('auth-middleware.ts'),
    )
  )
    .map(posixRelative)
    .sort((left, right) => left.localeCompare(right));

  const routeMap = new Map();
  for (const relativePath of routeFiles) {
    const contents = await readFile(path.join(rootDir, relativePath), 'utf8');
    for (const route of collectRouteMatches(contents)) {
      const key = `${route.method} ${route.path} ${relativePath}`;
      routeMap.set(key, {
        ...route,
        source: relativePath,
      });
    }
  }

  const routes = [...routeMap.values()];

  routes.sort((left, right) => {
    const pathOrder = left.path.localeCompare(right.path);
    if (pathOrder !== 0) return pathOrder;
    const methodOrder = left.method.localeCompare(right.method);
    if (methodOrder !== 0) return methodOrder;
    return left.source.localeCompare(right.source);
  });

  const lines = [
    formatGeneratedHeader(
      'Batch Backend Route Index',
      'Provide a quick inventory of Fastify route registrations in `@esl-pipeline/batch-backend` without repeating the contract semantics already described in SSOT and runbooks.',
      'Routes are extracted from route registration files under `packages/batch-backend/src/transport/` by matching direct `app.<method>(...)` registrations.',
    ),
    '## Routes',
    '',
    '| Method | Path | Source |',
    '| --- | --- | --- |',
    ...routes.map((route) => `| ${route.method} | \`${route.path}\` | \`${route.source}\` |`),
    '',
  ];

  await writeGenerated('docs/generated/backend-route-index.md', lines.join('\n'));
}

await generatePackageReadmeIndex();
await generatePlansIndex({
  repoRoot: rootDir,
  config: docsCheckConfig,
  sourceCommand: 'pnpm docs:generate:indexes',
});
await generateBackendRouteIndex();
await generateEnvSurfaceIndex();
