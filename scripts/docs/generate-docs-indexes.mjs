import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const generatedDir = path.join(rootDir, 'docs', 'generated');
const docsCheckConfigPath = path.join(rootDir, 'scripts', 'docs', 'docs-check.config.json');

const docsCheckConfig = JSON.parse(await readFile(docsCheckConfigPath, 'utf8'));
const enforcedDocs = new Set([...(docsCheckConfig.non_core_docs ?? []), ...(docsCheckConfig.active_ops_docs ?? [])]);

async function walk(relativeDir, matcher) {
  const absoluteDir = path.join(rootDir, relativeDir);
  const entries = await readdir(absoluteDir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relativePath = path.posix.join(relativeDir.replaceAll(path.sep, '/'), entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(relativePath, matcher)));
      continue;
    }
    if (!matcher(relativePath)) {
      continue;
    }
    files.push(relativePath);
  }
  return files;
}

async function readMarkdownTitle(relativePath) {
  const contents = await readFile(path.join(rootDir, relativePath), 'utf8');
  const match = contents.match(/^#\s+(.+)$/m);
  return match ? match[1].trim() : path.basename(relativePath);
}

async function writeGenerated(relativePath, contents) {
  await writeFile(path.join(rootDir, relativePath), contents, 'utf8');
}

function posixRelative(relativePath) {
  return relativePath.replaceAll(path.sep, '/');
}

function formatGeneratedHeader(title, purpose, sourceNote) {
  return [
    `# ${title}`,
    '',
    '> Generated by `pnpm docs:generate:indexes`. Do not edit by hand.',
    '',
    '## Purpose',
    '',
    `- ${purpose}`,
    `- ${sourceNote}`,
    '',
  ].join('\n');
}

async function generatePackageReadmeIndex() {
  const packageDirs = (await readdir(path.join(rootDir, 'packages'), { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right));

  const rows = [];
  for (const packageDir of packageDirs) {
    const readmePath = posixRelative(path.join('packages', packageDir, 'README.md'));
    const packageJsonPath = path.join(rootDir, 'packages', packageDir, 'package.json');
    try {
      await stat(path.join(rootDir, readmePath));
    } catch {
      continue;
    }
    const packageJson = JSON.parse(await readFile(packageJsonPath, 'utf8'));
    const title = await readMarkdownTitle(readmePath);
    rows.push({
      packageName: packageJson.name ?? packageDir,
      title,
      path: readmePath,
      enforced: enforcedDocs.has(readmePath) ? 'yes' : 'no',
    });
  }

  const lines = [
    formatGeneratedHeader(
      'Package README Index',
      'Provide a fast inventory of package-level README surfaces and whether they are part of the current docs enforcement scope.',
      'Package names come from `packages/*/package.json`; enforcement scope comes from `scripts/docs/docs-check.config.json`.',
    ),
    '## Packages',
    '',
    '| Package | README Title | Enforced | Path |',
    '| --- | --- | --- | --- |',
    ...rows.map(
      (row) => `| \`${row.packageName}\` | ${row.title} | ${row.enforced} | \`${row.path}\` |`,
    ),
    '',
  ];

  await writeGenerated('docs/generated/package-readme-index.md', lines.join('\n'));
}

function classifyPlanPath(relativePath) {
  if (relativePath === 'docs/plans/README.md') return 'router';
  if (relativePath.startsWith('docs/plans/completed/')) return 'completed';
  if (relativePath.startsWith('docs/plans/backlog/')) return 'backlog';
  if (path.posix.dirname(relativePath) === 'docs/plans') return 'standalone';
  if (path.posix.basename(relativePath) === 'README.md') return 'topic';
  return 'phase/detail';
}

async function generatePlansIndex() {
  const planFiles = (await walk('docs/plans', (relativePath) => relativePath.endsWith('.md')))
    .map(posixRelative)
    .sort((left, right) => left.localeCompare(right));

  const rows = [];
  for (const relativePath of planFiles) {
    rows.push({
      kind: classifyPlanPath(relativePath),
      title: await readMarkdownTitle(relativePath),
      path: relativePath,
    });
  }

  const lines = [
    formatGeneratedHeader(
      'Plans Index',
      'Provide a flat inventory of plan docs so agents can find the right roadmap, execution phase, or completed work artifact quickly.',
      'Plan kinds are inferred from the file path under `docs/plans/`.',
    ),
    '## Plan Files',
    '',
    '| Kind | Title | Path |',
    '| --- | --- | --- |',
    ...rows.map((row) => `| ${row.kind} | ${row.title} | \`${row.path}\` |`),
    '',
  ];

  await writeGenerated('docs/generated/plans-index.md', lines.join('\n'));
}

function collectRouteMatches(contents) {
  const regex = /app\.(get|post|put|patch|delete)\(\s*['"`]([^'"`]+)['"`]/g;
  const matches = [];
  let match;
  while ((match = regex.exec(contents)) !== null) {
    matches.push({
      method: match[1].toUpperCase(),
      path: match[2],
    });
  }
  return matches;
}

async function generateBackendRouteIndex() {
  const routeFiles = (await walk('packages/batch-backend/src/transport', (relativePath) =>
    relativePath.endsWith('.ts') && !relativePath.endsWith('auth-middleware.ts'),
  ))
    .map(posixRelative)
    .sort((left, right) => left.localeCompare(right));

  const routeMap = new Map();
  for (const relativePath of routeFiles) {
    const contents = await readFile(path.join(rootDir, relativePath), 'utf8');
    for (const route of collectRouteMatches(contents)) {
      const key = `${route.method} ${route.path} ${relativePath}`;
      routeMap.set(key, {
        ...route,
        source: relativePath,
      });
    }
  }

  const routes = [...routeMap.values()];

  routes.sort((left, right) => {
    const pathOrder = left.path.localeCompare(right.path);
    if (pathOrder !== 0) return pathOrder;
    const methodOrder = left.method.localeCompare(right.method);
    if (methodOrder !== 0) return methodOrder;
    return left.source.localeCompare(right.source);
  });

  const lines = [
    formatGeneratedHeader(
      'Batch Backend Route Index',
      'Provide a quick inventory of Fastify route registrations in `@esl-pipeline/batch-backend` without repeating the contract semantics already described in SSOT and runbooks.',
      'Routes are extracted from route registration files under `packages/batch-backend/src/transport/` by matching direct `app.<method>(...)` registrations.',
    ),
    '## Routes',
    '',
    '| Method | Path | Source |',
    '| --- | --- | --- |',
    ...routes.map((route) => `| ${route.method} | \`${route.path}\` | \`${route.source}\` |`),
    '',
  ];

  await writeGenerated('docs/generated/backend-route-index.md', lines.join('\n'));
}

await generatePackageReadmeIndex();
await generatePlansIndex();
await generateBackendRouteIndex();
