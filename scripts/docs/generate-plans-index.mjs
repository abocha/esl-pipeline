#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildPlanIndexRows } from './plan-lifecycle-lib.mjs';

const defaultRootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

export async function generatePlansIndex({
  repoRoot = defaultRootDir,
  config,
  sourceCommand = 'pnpm docs:generate:plans-index',
} = {}) {
  const docsConfig =
    config ??
    JSON.parse(
      await readFile(path.join(repoRoot, 'scripts', 'docs', 'docs-check.config.json'), 'utf8'),
    );
  const rows = buildPlanIndexRows({ repoRoot, config: docsConfig });

  const lines = [
    formatGeneratedHeader(
      'Plans Index',
      'Provide a lifecycle-aware inventory of plan docs so agents can distinguish editable execution plans from archived historical trace.',
      'Plan lifecycle, routing, editability, and current focus come from `docs/plans/README.md`, plan metadata, and archive location.',
      sourceCommand,
    ),
    '## Plan Files',
    '',
    '| Kind | Title | Status | Routed | Editable | Current Focus | Exit Trigger | Path |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (row) =>
        `| ${row.kind} | ${row.title} | ${row.status || ''} | ${row.routed} | ${row.editable} | ${row.currentFocus || ''} | ${row.exitTrigger || ''} | \`${row.path}\` |`,
    ),
    '',
  ];

  await writeFile(path.join(repoRoot, 'docs', 'generated', 'plans-index.md'), lines.join('\n'), {
    encoding: 'utf8',
  });
}

function formatGeneratedHeader(title, purpose, sourceNote, sourceCommand) {
  return [
    `# ${title}`,
    '',
    `> Generated by \`${sourceCommand}\`. Do not edit by hand.`,
    '',
    '## Purpose',
    '',
    `- ${purpose}`,
    `- ${sourceNote}`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generatePlansIndex();
}
